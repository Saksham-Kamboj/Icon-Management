export default function Icon({
  name,
  size = "1em",
  style = {},
  className = "",
}) {
  if (!name) return null;

  // Get the icon component from the map
  const IconComponent = iconMap[name];
  if (!IconComponent) {
    if (typeof console !== "undefined") {
      console.warn(
        `[Icon] Icon "${name}" is not available in Icon.jsx. Please add it to iconMap or use an existing valid icon.`
      );
    }
    // Graceful fallback to avoid crashing the entire application/page
    const FallbackComponent = iconMap["help-circle"] || iconMap["alert-circle"];
    if (!FallbackComponent) return null;

    const iconSize =
      typeof size === "string" && size.includes("px")
        ? Number.parseInt(size.replace("px", ""))
        : size;

    return (
      <FallbackComponent
        className={className}
        style={{
          fontSize: iconSize,
          width: iconSize,
          height: iconSize,
          display: "inline-flex",
          alignItems: "center",
          justifyContent: "center",
          opacity: 0.5,
          ...style,
        }}
        aria-label={`missing-icon-${name}`}
      />
    );
  }

  // Convert size to number if it's a string with 'px'
  const iconSize =
    typeof size === "string" && size.includes("px")
      ? Number.parseInt(size.replace("px", ""))
      : size;

  return (
    <IconComponent
      className={className}
      style={{
        fontSize: iconSize,
        width: iconSize,
        height: iconSize,
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        ...style,
      }}
      aria-label={name}
    />
  );
}

const getIconPackage = (name) => {
  const comp = iconMap[name];
  if (!comp) return "react-icons";
  const cName = comp.displayName || comp.name || "";
  const match = cName.match(/^([A-Z][a-z0-9]*?)(?=[A-Z0-9]|$)/);
  const prefix = match ? match[1].toLowerCase() : "";
  return prefix ? `react-icons/${prefix}` : "react-icons";
};

const iconNames = Object.keys(iconMap);

// Dynamically group all icons by their react-icons sub-library package
const iconGroups = Object.keys(iconMap).reduce((acc, name) => {
  const pkg = getIconPackage(name);
  if (!acc[pkg]) acc[pkg] = [];
  acc[pkg].push(name);
  return acc;
}, {});

export { iconMap, iconNames, iconGroups, getIconPackage };